// What a host remembers between runs, and the one place that writes it down.
//
// `PairingRecord.cs` is the .NET half and the rules are its rules: who may be
// admitted, what spends an invitation, what unpairing withdraws, and what a
// lowered peer limit drops. They are a security boundary — every admitted
// machine reaches the application's handlers — so they are ported rather than
// reinvented, and the reasons stay with them.
//
// Every decision is made synchronously on the state in memory and only then
// written, so two machines arriving at once cannot both be told yes with only
// the first written down: one of them runs to the end first.

import { base64urlEncode } from "./address.js";

/// 128 bits: not guessable, and still a code somebody can read aloud.
const TOKEN_BYTES = 16;

/// The stored shape. A store written by a newer version is refused rather
/// than read as this one, which would lose whatever that version added.
export const STATE_VERSION = 1;

/// Mints an invitation good for `lifetimeMs` from `now`.
export function newOffer({ lifetimeMs, now, label = null, singleUse = false }) {
  return {
    id: crypto.randomUUID(),
    token: base64urlEncode(crypto.getRandomValues(new Uint8Array(TOKEN_BYTES))),
    expiresAt: now + lifetimeMs,
    label,
    singleUse,
  };
}

const expired = (offer, now) => now >= offer.expiresAt;

// In a time that says nothing about how much of the token was right.
function matches(offer, token) {
  if (typeof token !== "string") return false;
  const expected = new TextEncoder().encode(offer.token);
  const given = new TextEncoder().encode(token);
  let difference = expected.length ^ given.length;
  for (let i = 0; i < expected.length; i++) difference |= expected[i] ^ (given[i] ?? 0);
  return difference === 0;
}

export class PairingRecord {
  #appName;
  #store;
  #state;
  #maxPeers;
  #now;
  #lastWrite = Promise.resolve();

  constructor({ appName, store, state, maxPeers, now }) {
    this.#appName = appName;
    this.#store = store;
    this.#state = state;
    this.#maxPeers = maxPeers;
    this.#now = now;
  }

  /// Reads what the store holds for `appName`, or starts from nothing.
  static async load({ appName, store, maxPeers = 1, now = Date.now }) {
    const saved = await store.load(appName);
    if (saved && saved.version > STATE_VERSION) {
      throw new Error(
        `the stored host for "${appName}" was written by a newer version (${saved.version}); ` +
          "refusing to read it rather than lose what it holds",
      );
    }
    const state = {
      version: STATE_VERSION,
      privateKey: saved?.privateKey ?? null,
      homeRegionId: saved?.homeRegionId ?? null,
      pairings: saved?.pairings ?? [],
      peers: saved?.peers ?? [],
    };
    return new PairingRecord({ appName, store, state, maxPeers, now });
  }

  get state() {
    return this.#state;
  }

  get peers() {
    return this.#state.peers;
  }

  get maxPeers() {
    return this.#maxPeers;
  }

  get now() {
    return this.#now();
  }

  get full() {
    return this.#state.peers.length >= this.#maxPeers;
  }

  /// The newest offer: what this host's published code is made of.
  get offer() {
    const { pairings } = this.#state;
    return pairings.length ? pairings[pairings.length - 1] : null;
  }

  /// The offers still worth handing out. Expired ones stay stored until the
  /// next is minted, and showing one would be a code pairing then refuses.
  get liveOffers() {
    const now = this.#now();
    return this.#state.pairings.filter((offer) => !expired(offer, now));
  }

  peerWith(key) {
    return this.#state.peers.find((peer) => peer.key === key) ?? null;
  }

  /// This machine's identity, generated by the caller the first time and
  /// never replaced: a new key is a new address, and every code is dead.
  setPrivateKey(privateKey) {
    return this.#update((current) => (current.privateKey ? null : { ...current, privateKey }));
  }

  /// Fixes the region for good, for the same reason as the key: the address
  /// is both, and a host that moved would strand every code it published.
  rememberHomeRegion(regionId) {
    return this.#update((current) =>
      current.homeRegionId === regionId ? null : { ...current, homeRegionId: regionId },
    );
  }

  /// The offer worth publishing, minted afresh when the last has run out.
  ///
  /// A host restarted inside the window keeps its code, because somebody may
  /// have written it down. A full one goes on showing the code it published,
  /// spent as it is: replacing it would publish a code nothing can use.
  async offerPairing(windowMs) {
    const offer = this.offer;
    if (offer && (this.full || !expired(offer, this.#now()))) return offer;
    return this.addOffer(newOffer({ lifetimeMs: windowMs, now: this.#now() }));
  }

  async addOffer(offer) {
    const now = this.#now();
    // Offers that ran out go, except the newest, which is still what the
    // published code is made of.
    await this.#update((current) => ({
      ...current,
      pairings: [
        ...current.pairings.filter(
          (kept, index) => index === current.pairings.length - 1 || !expired(kept, now),
        ),
        offer,
      ],
    }));
    return offer;
  }

  async revokeOffer(id) {
    let found = false;
    await this.#update((current) => {
      found = current.pairings.some((offer) => offer.id === id);
      return found ? { ...current, pairings: current.pairings.filter((offer) => offer.id !== id) } : null;
    });
    return found;
  }

  /// Unpairs one machine. The invitation it was admitted by goes with it: the
  /// machine still holds that code and reconnects on its own, so a live offer
  /// would let it straight back in as a stranger with a valid token. A
  /// reusable offer is withdrawn for everyone it was shown to, because letting
  /// the forgotten machine back in is the worse of the two costs.
  async forgetPeer(key) {
    let found = false;
    await this.#update((current) => {
      const known = current.peers.find((peer) => peer.key === key);
      if (!known) return null;
      found = true;
      return {
        ...current,
        peers: current.peers.filter((peer) => peer.key !== key),
        pairings: current.pairings.filter((offer) => offer.id !== known.invitationId),
      };
    });
    return found;
  }

  /// Unpairs whatever a lowered limit no longer has room for, keeping the
  /// machines seen most recently. The limit is a security bound, so a store
  /// written under a larger one cannot simply be honoured; the invitations
  /// the dropped machines came in by go too, or unpairing another device
  /// would let one of them straight back.
  async enforcePeerLimit() {
    let dropped = [];
    await this.#update((current) => {
      if (current.peers.length <= this.#maxPeers) return null;
      const kept = new Set(
        [...current.peers]
          .sort((a, b) => b.lastSeen - a.lastSeen)
          .slice(0, this.#maxPeers)
          .map((peer) => peer.key),
      );
      dropped = current.peers.filter((peer) => !kept.has(peer.key));
      const withdrawn = new Set(dropped.map((peer) => peer.invitationId).filter(Boolean));
      return {
        ...current,
        peers: current.peers.filter((peer) => kept.has(peer.key)),
        pairings: current.pairings.filter((offer) => !withdrawn.has(offer.id)),
      };
    });
    return dropped;
  }

  /// Decides whether the machine with `key` may stay.
  ///
  /// Pairing is trust on first use, but not on any use: a known machine is
  /// let in by its key, a stranger only with a live token and room to spare.
  /// `lapsed` is for this end's operator, never for the machine outside: the
  /// token was one this host did offer, and its window has closed.
  ///
  /// @returns `{ admitted, lapsed }`, where `admitted` is the stored peer or null.
  async admit(key, { pairingToken, displayName }) {
    const now = this.#now();
    let admitted = null;
    let lapsed = false;
    const write = this.#update((current) => {
      const known = current.peers.find((peer) => peer.key === key);
      const invitation = current.pairings.find((offer) => !expired(offer, now) && matches(offer, pairingToken));
      if (!known && (current.peers.length >= this.#maxPeers || !invitation)) {
        lapsed =
          current.peers.length < this.#maxPeers &&
          current.pairings.some((offer) => expired(offer, now) && matches(offer, pairingToken));
        return null;
      }

      const peers = known
        ? current.peers.map((peer) =>
            peer.key === key ? { ...peer, name: displayName ?? peer.name, lastSeen: now } : peer,
          )
        : [
            ...current.peers,
            { key, name: displayName ?? null, pairedAt: now, lastSeen: now, invitationId: invitation.id },
          ];
      admitted = peers.find((peer) => peer.key === key);
      const spent = !known && invitation.singleUse ? invitation.id : null;
      return {
        ...current,
        peers,
        pairings: spent ? current.pairings.filter((offer) => offer.id !== spent) : current.pairings,
      };
    });
    // Answered only once it is written: a pairing the store lost on the way
    // is a machine that is paired today and a stranger after a restart.
    await write;
    return { admitted, lapsed };
  }

  /// Resolves once every write already decided has reached the store,
  /// whether or not it succeeded.
  settled() {
    return this.#lastWrite.catch(() => {});
  }

  // The change is decided at once and its write queued behind the previous
  // one, so the store ends up in the order the states were decided in: two
  // writes racing could leave the older state there after a restart, which is
  // a pairing lost.
  #update(change) {
    const next = change(this.#state);
    // Nothing to write is nothing to wait for, least of all an earlier write
    // that failed and is somebody else's to report.
    if (!next) return Promise.resolve();
    this.#state = next;
    const write = this.#lastWrite.catch(() => {}).then(() => this.#store.save(this.#appName, next));
    this.#lastWrite = write;
    return write;
  }
}
